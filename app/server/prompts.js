export function buildSystemPrompt({ tradition, topics, memorySnippets, recentTurns }) {
  const t = TRADITION_PROMPTS[tradition] || TRADITION_PROMPTS.common;
  const topicKeys = topics?.length ? topics : ['마음'];
  const topicBlocks = topicKeys
    .map((k) => {
      const tp = TOPIC_PROMPTS[k] || TOPIC_PROMPTS.마음;
      return `- ${k}: ${tp.focus} / ${tp.guide} / 반영 시: ${tp.reflect}`;
    })
    .join('\n');

  const memLines = (memorySnippets || [])
    .slice(0, 5)
    .map((m) => `· ${m.label || m.summary || m}`)
    .join('\n');

  const turnLines = (recentTurns || [])
    .slice(-6)
    .map((m) => `${m.role === 'you' || m.role === 'user' ? '사용자' : '공명'}: ${m.text}`)
    .join('\n');

  return `당신은 '공명 스테이션'의 AI 다리(Bridge)입니다.
신이 아니며 사제·목사·스님도 아닙니다. 평가·가르치기·진단·개종·기부 유도 금지. 공명 경험의 진위·크기·등급을 판정·점수화·인증하지 않는다. 화면 파동을 구원·성스러움·가치의 증거로 말하지 않는다.
삶의 가치를 판결하지 않는다. 「가치 있다/없다」「목적이 없으니 무의미하다」「의미를 찾아라」로 닫지 않는다. 기본적 가치와 흔적·성취·유용성을 섞어 말하지 않는다. 허무를 느끼더라도 삶 전체를 무가치하다고 단정하지 않는다. 행위의 잘못을 듣더라도 그 사람을 선인/악인으로 고정하거나 삶 전체를 무가치하다고 판결하지 않는다. 용서·화해를 강요하지 않는다.

[문체 — 중요]
- 추상적 AI 감성 금지: “여기 두셔도”, “머물러도 괜찮”, “충분합니다”, “울림”, “결” 등.
- 1문장은 반드시 사용자의 구체적 내용(사람·몸·사건)을 되받을 것.
- 그다음 1~2문장은 짧고 건조한 동행. 전통이 있으면 실제로 쓰이는 짧은 말 하나만.

[역할]
1) reflection: 경청 반영 1문장 (왜곡·미화 없이)
2) comfort: 짧은 위로 2~3문장. 질문이면 정답을 만들지 말고 질문을 되받는다.
3) followup_invite: 방금 말의 한 장면만 묻는 질문 1문장. "더 말씀하셔도 됩니다" 같은 빈 초대는 쓰지 않는다.
이전 대화가 있으면 새 주제로 시작하지 말고, 그 말의 다음 장면(사람·상황·감정)을 묻는다.
총 분량: 한국어 존댓말 2~5문장. 명령·잔소리·해결책·설교 금지.
나이·효도·통증 이야기로 단정하지 말 것. 청년·직장·믿음·용서·미움도 같은 무게로 듣는다.

[전통: ${t.name}]
톤: ${t.voice}
해야 할 것: ${t.do.map((x) => `· ${x}`).join(' ')}
하지 말 것: ${t.avoid.join(', ')}
마무리 결: ${t.closing}

[주제별 가이드]
${topicBlocks}

[개인 메모리 — 요약만. 단정·추궁 금지]
${memLines || '이전 기억 없음.'}

[최근 대화]
${turnLines || '이번이 첫 말씀.'}

JSON만 출력:
{"reflection":"...","comfort":"...","followup_invite":"..."|null}`;
}

export function templateByTraditionTopic({ transcript, tradition, memory, topics }) {
  const t = TRADITION_PROMPTS[tradition] || TRADITION_PROMPTS.common;
  const tags = topics?.length ? topics : ['마음'];
  const primary = tags[0];
  const tp = TOPIC_PROMPTS[primary] || TOPIC_PROMPTS.마음;
  const nameHint = memory?.[0]?.label;
  const raw = String(transcript || '').trim();
  const short = raw.length > 42 ? `${raw.slice(0, 42)}…` : raw;

  const reflectionByTradition = {
    common:
      primary === '통증'
        ? '몸의 아픔 때문에 밤이 길게 느껴지시는군요.'
        : primary === '외로움'
          ? '혼자 감당하시는 기분이 드시는군요.'
          : primary === '그리움' || primary === '애도'
            ? '보고 싶은 마음이 아직 남아 있으시군요.'
            : short
              ? `「${short}」— 그렇게 말씀해 주셨습니다.`
              : '듣고 있습니다.',
    catholic: short
      ? `「${short}」 그 한숨을 듣고 있습니다.`
      : '그 한숨을 듣고 있습니다.',
    protestant: short
      ? `「${short}」 그 무게를 듣고 있습니다.`
      : '그 무거운 마음을 듣고 있습니다.',
    buddhist: '괴로움이 있음을, 있는 그대로 듣겠습니다.',
    won: short ? `오늘의 힘듦—「${short}」—있는 그대로 듣겠습니다.` : '오늘의 힘듦을 있는 그대로 듣겠습니다.',
  };

  const reflection = nameHint
    ? `${reflectionByTradition[tradition] || reflectionByTradition.common} (전에 말씀하신 「${nameHint}」도 마음에 남아 있습니다.)`
    : reflectionByTradition[tradition] || reflectionByTradition.common;

  const base = {
    common: '혼자 견디기 힘드셨겠습니다. 이어서 말씀하셔도, 여기서 멈추셔도 됩니다.',
    catholic: '고통이 당신 탓이라는 뜻은 아닙니다. 마음에 평화를 빕니다.',
    protestant: '무거운 짐, 혼자 지지 마십시오. 정죄하지 않겠습니다.',
    buddhist: '없애려 서두르지 않겠습니다. 있는 그대로 들었습니다.',
    won: '억지로 밝아지실 필요 없습니다. 있는 그대로 들었습니다.',
  };

  const topicLine = {
    통증: '몸의 아픔이 밤을 길게 만들 수 있습니다.',
    수면: '잠이 달아난 밤도 이상해서만이 아닙니다.',
    그리움: '보고 싶은 마음은 쉽게 지워지지 않습니다.',
    애도: '빈자리가 크게 느껴지는 날입니다.',
    가족: '가족 일은 한 줄로 설명되지 않습니다.',
    직장: '일로 닳으신 상태도 듣겠습니다. 성과로 재지 않습니다.',
    외로움: '혼자라는 느낌이 드실 때입니다.',
    우울: '마음이 가라앉아 있으실 때입니다.',
    막막함: '앞이 안 보일 때 더 무겁습니다.',
    인생: '삶이 버겁게 느껴지는 날입니다.',
    섭섭함: '서운한 마음은 사소해서 아픈 것이 아닙니다.',
    불안: '막막함이 몸을 조일 수 있습니다.',
    청년: '앞길이 흐려도 지금의 무게를 작게 말하지 않겠습니다.',
    신앙: '기도의 침묵을 벌이나 불신앙으로 설명하지 않겠습니다.',
    용서: '지금 당장 사과하라고 하지 않겠습니다.',
    미움: '미운 마음을 악한 사람의 증거로 받지 않겠습니다.',
    의미: '일자리와 당신의 자리를 같은 것으로 받지 않겠습니다.',
    감사: '고마운 일을 교리로 바꾸지 않고 듣겠습니다.',
    돌봄피로: '돌보시느라 지치신 것도 듣겠습니다.',
    마음: tp.reflect,
  };

  let comfort = `${topicLine[primary] || topicLine.마음} ${base[tradition] || base.common}`;
  const followup = memory?.[0]
    ? `지난번 「${memory[0].label}」와 오늘의 말이 이어집니까, 다른 일입니까?`
    : short
      ? `방금 말씀 가운데, 가장 걸리는 부분만 더 말씀해 주십시오.`
      : '지금 마음에 걸리는 장면이 있으면 그 장면만 말씀해 주십시오.';

  return {
    reflection,
    comfort: comfort.slice(0, 320),
    followup_invite: followup,
    provider: 'template',
    _tradition: t.name,
  };
}
